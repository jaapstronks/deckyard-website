#!/usr/bin/env node
// Current-backlog audit: which screenshots are already stale?
//
// A screenshot is stale if the core source it documents changed AFTER the
// screenshot was captured. Unlike the content-hash tripwire (which baselines
// "now"), this uses git history in the core repo against each artifact's
// `capturedAt` date — so it surfaces the EXISTING backlog, not just future drift.
//
//   node docs-sync/audit-since-capture.mjs            # ranked console report
//   node docs-sync/audit-since-capture.mjs --report   # also (re)writes STALENESS.md
//
// Read-only: runs `git log` in the core repo, touches nothing there.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');
const registry = JSON.parse(readFileSync(join(HERE, 'registry.json'), 'utf8'));
const CORE = resolve(REPO_ROOT, registry.coreRepo || '../deckyard');
const REPORT = process.argv.includes('--report');

if (!existsSync(join(CORE, '.git'))) {
  console.error(`core repo (with .git) not found at ${CORE}`);
  process.exit(2);
}

// Count core commits touching `sources` since `sinceDate` (YYYY-MM-DD).
function commitsSince(sinceDate, sources) {
  if (!sources.length) return { count: 0, last: null };
  try {
    const out = execFileSync(
      'git',
      ['-C', CORE, 'log', `--since=${sinceDate} 00:00:00`, '--format=%ad', '--date=short', '--', ...sources],
      { encoding: 'utf8' }
    ).trim();
    if (!out) return { count: 0, last: null };
    const dates = out.split('\n');
    return { count: dates.length, last: dates[0] };
  } catch {
    return { count: 0, last: null };
  }
}

const shots = registry.artifacts.filter((a) => a.type === 'screenshot');
const rows = shots.map((a) => {
  const { count, last } = commitsSince(a.capturedAt, a.sources || []);
  return { ...a, commitsSince: count, lastChange: last };
});

// Rank: most core churn since capture first; age as tiebreaker.
rows.sort((a, b) => b.commitsSince - a.commitsSince || a.capturedAt.localeCompare(b.capturedAt));

const stale = rows.filter((r) => r.commitsSince > 0);
const fresh = rows.filter((r) => r.commitsSince === 0);

const tier = (n) => (n >= 10 ? 'HIGH' : n >= 3 ? 'MED' : 'LOW');

console.log(`\nScreenshot backlog audit — core churn since each capture date\n`);
console.log(`  ${stale.length} screenshots have source changes since capture; ${fresh.length} look current.\n`);
for (const r of stale) {
  const name = r.path.split('/').pop();
  console.log(
    `  [${tier(r.commitsSince).padEnd(4)}] ${String(r.commitsSince).padStart(3)} commits since ${r.capturedAt}  ` +
      `${name}  → ${r.docPages.map((p) => p.replace('docs/', '')).join(', ')}`
  );
}
console.log('');

if (REPORT) {
  const lines = [];
  lines.push('# Docs staleness — current backlog');
  lines.push('');
  lines.push('Generated by `node docs-sync/audit-since-capture.mjs --report`. Ranks existing');
  lines.push('screenshots by how much core source changed **since the screenshot was captured**.');
  lines.push('HIGH = 10+ commits, MED = 3-9, LOW = 1-2. Re-capture top-down.');
  lines.push('');
  lines.push(`**${stale.length}** screenshots with changed source · **${fresh.length}** current (of ${rows.length}).`);
  lines.push('');
  lines.push('| tier | commits since capture | last core change | captured | screenshot | doc page(s) |');
  lines.push('|---|--:|---|---|---|---|');
  for (const r of stale) {
    const name = r.path.split('/').pop();
    lines.push(
      `| ${tier(r.commitsSince)} | ${r.commitsSince} | ${r.lastChange || ''} | ${r.capturedAt} | \`${name}\` | ${r.docPages.map((p) => p.replace('docs/', '')).join('<br>')} |`
    );
  }
  lines.push('');
  lines.push('## Current screenshots (no source change since capture)');
  lines.push('');
  for (const r of fresh) lines.push(`- \`${r.path.split('/').pop()}\` (${r.capturedAt})`);
  lines.push('');
  writeFileSync(join(HERE, 'STALENESS.md'), lines.join('\n') + '\n');
  console.log('  wrote docs-sync/STALENESS.md\n');
}
